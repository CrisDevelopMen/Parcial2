def norm_type(t):
    t = (t or "").lower()
    if t.startswith(("varchar", "char")) or t == "string":
        return "string"
    if t in ("tinyint", "smallint", "int", "integer", "bigint", "long", "short"):
        return "int"
    if t.startswith(("decimal", "double", "float")):
        return "double"
    return t
