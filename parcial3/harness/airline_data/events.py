def encode(e) -> bytes:
    return json.dumps(e, separators=(",", ":")).encode()


# --------------------------------------------------------------------------------------- oracle
class StarTruth:
    def __init__(self, seed, n=20000, salt=0):
        self.seed = seed
        self.arrivals, self.unique = make_events(seed, n, salt)
        self.hist = category_history(seed)
        self.routes = routes_ref(seed)
        ev = pd.DataFrame(self.unique)
        ev["date"] = ev.event_ts.str[:10]
        ev["year"] = ev.date.str[:4].astype(int)
        ev["month"] = ev.date.str[5:7].astype(int)
        ev["ym"] = ev.date.str[:7]
        ev["is_weekend"] = pd.to_datetime(ev.date).dt.dayofweek >= 5
        cal = calendar_dates().set_index("full_date")
        ev["weekday_name"] = ev.date.map(cal.weekday_name)
        ev["is_holiday"] = ev.date.map(cal.is_holiday).astype(bool)
        ev["is_long_weekend"] = ev.date.map(cal.is_long_weekend).astype(bool)
        s = ev[ev.event_type == "search_performed"].copy()
        s["route"] = s.origin + "-" + s.destination
        self.searches = s[["event_id", "date", "year", "month", "ym", "is_weekend", "weekday_name", "is_holiday", "is_long_weekend",
                           "route", "results_count"]]
        b = ev[ev.event_type != "search_performed"].copy()
        b["bookings"] = (b.event_type == "reservation_created").astype(int)
        b["cancellations"] = (b.event_type == "reservation_cancelled").astype(int)
        b["revenue_cents"] = b.price_cents * (b.bookings - b.cancellations)
        b["route_category"] = [category_on(self.hist, r, d) for r, d in zip(b.route, b.date)]
        self.bookings = b[["event_id", "event_type", "date", "year", "month", "ym", "is_weekend", "weekday_name", "is_holiday",
                           "is_long_weekend", "route", "fare_class",
                           "route_category", "bookings", "cancellations", "revenue_cents"]]

    # the six business questions
    def q1(self):   # net revenue by year, month, fare class
        g = self.bookings.groupby(["year", "month", "fare_class"]).revenue_cents.sum().reset_index()
        return {(int(r.year), int(r.month), r.fare_class): int(r.revenue_cents) for r in g.itertuples()}

    def q2(self):   # cancellations and bookings per route
        g = self.bookings.groupby("route")[["cancellations", "bookings"]].sum()
        return {k: (int(v.cancellations), int(v.bookings)) for k, v in g.iterrows()}

    def q3(self):   # bookings per weekday name
        g = self.bookings.groupby("weekday_name").bookings.sum()
        return {k: int(v) for k, v in g.items()}

    def q7(self):   # searches and bookings on holidays vs other days
        s = self.searches.groupby("is_holiday").size()
        b = self.bookings.groupby("is_holiday").bookings.sum()
        return {bool(k): (int(s.get(k, 0)), int(b.get(k, 0))) for k in (False, True)}

    def q8(self):   # bookings on long-weekend days vs other days
        g = self.bookings.groupby("is_long_weekend").bookings.sum()
        return {bool(k): int(g.get(k, 0)) for k in (False, True)}

    def q4(self, k=10):
        g = self.bookings.groupby("route").revenue_cents.sum().reset_index()
        g = g.sort_values(["revenue_cents", "route"], ascending=[False, True]).head(k)
        return [(r.route, int(r.revenue_cents)) for r in g.itertuples()]

    def q5(self):   # net revenue by as-of route category, year, month
        g = self.bookings.groupby(["route_category", "year", "month"]).revenue_cents.sum().reset_index()
        return {(r.route_category, int(r.year), int(r.month)): int(r.revenue_cents) for r in g.itertuples()}

    def q6(self):   # searches and bookings per route
        s = self.searches.groupby("route").size()
        b = self.bookings.groupby("route").bookings.sum()
        return {r: (int(s.get(r, 0)), int(b.get(r, 0))) for r in set(s.index) | set(b.index)}

    def per_date_counts(self):
        return {"search": self.searches.groupby("date").size().to_dict(),
                "booking": self.bookings.groupby("date").size().to_dict()}

    @property
    def n_search_unique(self):
        return len(self.searches)

    @property
    def n_booking_unique(self):
        return len(self.bookings)


